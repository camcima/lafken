import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import type { Plugin, ResolvedConfig } from "vite";

/**
 * Minimal `.env` parser — handles `KEY=value`, `# comments`, blank lines, and
 * surrounding `'`/`"` quotes. Does not support multiline values, variable
 * expansion (`${FOO}`), or escape sequences. Sufficient for this project's
 * `.env.example` shape; if requirements grow, swap for `dotenv.parse`.
 */
function parseEnvFile(content: string): Record<string, string> {
  const result: Record<string, string> = {};
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    result[key] = value;
  }
  return result;
}

/**
 * Vite plugin that generates `public/config.js` from `VITE_*` environment
 * variables during development.
 *
 * Only runs in dev (`apply: "serve"`) — production builds are unaffected.
 * The generated file has the same shape as `config.js.template` so that
 * `getRuntimeValue()` works identically in dev and prod.
 *
 * Source precedence (later overrides earlier):
 *   1. `.env.example` — committed defaults; safe baseline for fresh checkouts.
 *   2. Vite's resolved env (`.env`, `.env.local`, mode-specific files,
 *      filtered `process.env`) — developer-specific overrides.
 *
 * Mapping: `VITE_API_URL=http://localhost:3000` → `API_URL: "http://localhost:3000"`
 *
 * Setup: `cp .env.example .env.local` and edit values as needed. With the
 * `.env.example` baseline in place, an empty or missing `.env.local` still
 * yields a working `config.js` — the app boots against committed defaults.
 */
export function devRuntimeConfigPlugin(): Plugin {
  return {
    name: "dev-runtime-config",
    apply: "serve",
    configResolved(config: ResolvedConfig) {
      const examplePath = resolve(config.root, ".env.example");
      const baseline = existsSync(examplePath)
        ? parseEnvFile(readFileSync(examplePath, "utf8"))
        : {};

      const merged: Record<string, string> = {
        ...baseline,
        ...(config.env as Record<string, string>),
      };

      const runtimeConfig: Record<string, string> = {};

      for (const [key, value] of Object.entries(merged)) {
        if (key.startsWith("VITE_")) {
          runtimeConfig[key.slice("VITE_".length)] = value;
        }
      }

      if (Object.keys(runtimeConfig).length === 0) {
        return;
      }

      const entries = Object.entries(runtimeConfig)
        .map(([key, value]) => `      ${key}: ${JSON.stringify(value)}`)
        .join(",\n");

      const configJs = `// Auto-generated by vite-dev-runtime-config plugin from .env.example + .env.local
// Do not edit — changes will be overwritten on dev server start.
(function () {
  if ("__APP_CONFIG__" in globalThis) {
    throw new Error("[security] __APP_CONFIG__ was already defined before config.js loaded");
  }

  Object.defineProperty(globalThis, "__APP_CONFIG__", {
    value: Object.freeze({
${entries}
    }),
    writable: false,
    configurable: false,
    enumerable: true,
  });
})();
`;

      writeFileSync(resolve(config.root, "public/config.js"), configJs);
    },
  };
}
