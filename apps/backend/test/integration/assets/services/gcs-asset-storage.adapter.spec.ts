import { readFileSync } from "node:fs";
import { join } from "node:path";

import { describe, expect, it } from "vitest";

import { GcsAssetStorageAdapter } from "@/assets/infrastructure/services/gcs-asset-storage.adapter";

const ENDPOINT = "http://localhost:4444";
const BINDING = { bucket: "lafken-dev", projectId: "lafken-dev" };
// eslint-disable-next-line no-process-env
const GATE = process.env["LAFKEN_E2E_REQUIRES_FAKE_GCS"] === "true";

// The credentials JSON wraps the same RSA key that fake-gcs uses to verify
// signatures via -private-key-location. Both sides must share this key so
// that v4-signed URLs generated by the SDK pass fake-gcs's verification.
const CREDENTIALS_JSON = readFileSync(
  join(__dirname, "../../../fixtures/fake-gcs-credentials.json"),
  "utf8",
);

describe.skipIf(!GATE)("GcsAssetStorageAdapter (fake-gcs)", () => {
  it("issues a v4 signed PUT URL accepted by fake-gcs", async () => {
    const adapter = new GcsAssetStorageAdapter({
      endpoint: ENDPOINT,
      credentialsJson: CREDENTIALS_JSON,
    });
    const key = `integration-test/${Date.now()}/source`;
    const result = await adapter.issueSignedUploadUrl({
      binding: BINDING,
      storageKey: key,
      contentType: "image/jpeg",
      maxBytes: 1_048_576n,
      ttlSeconds: 900,
    });
    expect(result.url).toContain("X-Goog-Signature");

    const putResponse = await fetch(result.url, {
      method: "PUT",
      headers: result.headers,
      body: new Uint8Array([0xff, 0xd8, 0xff]),
    });
    expect(putResponse.ok).toBe(true);

    expect(await adapter.objectExists({ binding: BINDING, storageKey: key })).toBe(true);
  });

  it("objectExists returns false for a key that was never PUT", async () => {
    const adapter = new GcsAssetStorageAdapter({ endpoint: ENDPOINT });
    expect(
      await adapter.objectExists({
        binding: BINDING,
        storageKey: `does-not-exist/${Date.now()}/source`,
      }),
    ).toBe(false);
  });

  it("signs a v4 read URL that fake-gcs serves the bytes from", async () => {
    const adapter = new GcsAssetStorageAdapter({
      endpoint: ENDPOINT,
      credentialsJson: CREDENTIALS_JSON,
    });
    // Upload an object first so we have something to read.
    const key = `integration-test/${Date.now()}/read-source`;
    const issued = await adapter.issueSignedUploadUrl({
      binding: BINDING,
      storageKey: key,
      contentType: "image/jpeg",
      maxBytes: 1_048_576n,
      ttlSeconds: 900,
    });
    const expected = new Uint8Array([0xde, 0xad, 0xbe, 0xef]);
    const putResponse = await fetch(issued.url, {
      method: "PUT",
      headers: issued.headers,
      body: expected,
    });
    expect(putResponse.ok).toBe(true);

    const readUrl = await adapter.signReadUrl({
      binding: BINDING,
      storageKey: key,
      ttlSeconds: 300,
    });
    expect(readUrl).toContain("X-Goog-Signature");

    const getResponse = await fetch(readUrl);
    expect(getResponse.ok).toBe(true);
    const bytes = new Uint8Array(await getResponse.arrayBuffer());
    expect(Array.from(bytes)).toEqual(Array.from(expected));
  });
});
