import {
  type ArgumentsHost,
  BadRequestException,
  Catch,
  type ExceptionFilter,
  HttpException,
  HttpStatus,
} from "@nestjs/common";
import { HttpAdapterHost } from "@nestjs/core";
import type { Response } from "express";

import { AppLoggerPort } from "@/shared/application/app-logger.port";
import { environmentConfiguration } from "@/shared/infrastructure/environment.configuration";
import {
  type DatabaseError,
  isDatabaseError,
} from "@/shared/infrastructure/persistence/database-error";
import { DomainError } from "@/shared/kernel/domain/errors/domain-error.interface";
import { ValidationError } from "@/shared/kernel/domain/errors/validation-error.interface";

export type IProblemDetailsJsonBody = {
  /**
   * A URI that identifies the specific instance of the error that occurred.
   * This can be useful for tracking the error and diagnosing problems.
   * Will be "about:blank" for generic errors.
   * Will be the `DomainError.errorCode` for domain errors.
   * Will be the `ValidationError.errorCode` for validation errors.
   */
  type: string;
  /**
   * A short, human-readable summary of the problem type.
   * It SHOULD NOT change from occurrence to occurrence of the problem,
   * except for purposes of localization.
   */
  title: string;
  /**
   * The HTTP status code generated by the origin server for this occurrence
   * of the problem.
   */
  status: number;
  /**
   * A detailed dynamic description of the error, suitable for displaying as
   * an error message to the end user.
   */
  detail?: string;
  error?: unknown;
  /**
   * For bad request exceptions, the list of invalid parameters.
   */
  errors?: string[];
  /**
   * The error code of the error.
   */
  code?: string;
  /**
   * The parameters of the error.
   */
  params?: Record<string, unknown>;
};

function resolveAppErrorHttpStatus(exception: DomainError | ValidationError): number {
  // Use direct instanceof so intermediate base classes (e.g. a project-level
  // BillingError extending DomainError) still resolve to the correct status.
  if (exception instanceof DomainError) {
    return HttpStatus.UNPROCESSABLE_ENTITY;
  }
  if (exception instanceof ValidationError) {
    return HttpStatus.BAD_REQUEST;
  }
  return HttpStatus.INTERNAL_SERVER_ERROR;
}

/**
 * This filter catches all exceptions that are not handled by other filters
 * and transforms them into a standardized HTTP in a RFC-7807-compliant format.
 * The HTTP responses with be in the `application/problem+json` media type.
 *
 * @see https://datatracker.ietf.org/doc/html/rfc7807
 */
@Catch()
export class CatchAllExceptionsForHttp implements ExceptionFilter {
  constructor(
    private readonly httpAdapterHost: HttpAdapterHost,
    private readonly logger: AppLoggerPort,
  ) {}

  private replyProblemDetailsJson(
    httpAdapter: HttpAdapterHost["httpAdapter"],
    responseRef: any,
    responseBody: IProblemDetailsJsonBody,
  ) {
    httpAdapter.setHeader(responseRef, "Content-Type", "application/problem+json");
    httpAdapter.reply(responseRef, responseBody, responseBody.status);
  }

  private composeResponseForDatabaseErrors(exception: DatabaseError) {
    const isDevelopment = environmentConfiguration.NODE_ENV === "development";

    const responseBody: IProblemDetailsJsonBody = {
      type: "about:blank",
      title: "Internal Server Error",
      status: 500,
    };

    // Driver/SQL details are useful locally but must never reach production
    // clients. Full error already logged server-side via this.logger.error.
    if (isDevelopment) {
      responseBody.detail = exception.message;
      responseBody.error = {
        name: exception.name,
        stack: exception.stack,
        cause: exception.cause,
      };
    }

    return responseBody;
  }

  private composeResponseForHttpExceptions(exception: HttpException) {
    const exceptionResponse = exception.getResponse();

    const isDevelopment = environmentConfiguration.NODE_ENV === "development";

    if (exception instanceof BadRequestException) {
      const messageField =
        typeof exceptionResponse === "object"
          ? (exceptionResponse as { message?: string | string[] }).message
          : undefined;
      const invalidParameters = Array.isArray(messageField)
        ? messageField
        : messageField
          ? [messageField]
          : undefined;
      const responseBody: IProblemDetailsJsonBody = {
        type: "about:blank",
        title: exception.name,
        status: exception.getStatus(),
        detail: exception.message,
        error: isDevelopment ? exception.cause : undefined,
        errors: invalidParameters,
      };

      return responseBody;
    }

    const responseBody: IProblemDetailsJsonBody = {
      type: "about:blank",
      title: exception.name,
      status: exception.getStatus(),
      detail: exception.message,
      error: isDevelopment ? exception.cause : undefined,
    };

    return responseBody;
  }

  private composeResponseForAppErrors(exception: DomainError | ValidationError) {
    const responseBody: IProblemDetailsJsonBody = {
      type: "about:blank",
      code: exception.errorCode,
      title: exception.name,
      status: resolveAppErrorHttpStatus(exception),
      detail: exception.message,
      params: exception.params,
    };

    return responseBody;
  }

  catch(exception: unknown, host: ArgumentsHost): void {
    this.logger.error(exception);

    const { httpAdapter } = this.httpAdapterHost;
    const ctx = host.switchToHttp();
    const response = ctx.getResponse<Response>();

    if (exception instanceof HttpException) {
      const responseBody = this.composeResponseForHttpExceptions(exception);

      const exceptionOriginalCause = exception.cause;
      if (
        exceptionOriginalCause &&
        // As we want to propagate the original application error `type` and `title`
        (exceptionOriginalCause instanceof DomainError ||
          exceptionOriginalCause instanceof ValidationError)
      ) {
        const causeResponseBody = this.composeResponseForAppErrors(exceptionOriginalCause);
        causeResponseBody.status = responseBody.status; // keeping the desired HTTP status code
        this.replyProblemDetailsJson(httpAdapter, response, causeResponseBody);
        response.locals.responseBody = causeResponseBody; // Exposing for further logging

        return;
      } else {
        this.replyProblemDetailsJson(httpAdapter, response, responseBody);
        response.locals.responseBody = responseBody; // Exposing for further logging

        return;
      }
    }

    if (exception instanceof DomainError || exception instanceof ValidationError) {
      const responseBody = this.composeResponseForAppErrors(exception);

      this.replyProblemDetailsJson(httpAdapter, response, responseBody);

      return;
    }

    if (exception && isDatabaseError(exception)) {
      const responseBody = this.composeResponseForDatabaseErrors(exception);

      this.replyProblemDetailsJson(httpAdapter, response, responseBody);

      return;
    }

    // For unknown exceptions, return a generic 500 Internal Server Error
    // The full error details are already logged server-side via this.logger.error(exception)
    const responseBody: IProblemDetailsJsonBody = {
      type: "about:blank",
      title: "Internal Server Error",
      status: 500,
    };

    if (
      environmentConfiguration.NODE_ENV === "development" &&
      typeof exception === "object" &&
      exception &&
      "message" in exception &&
      typeof exception.message === "string"
    ) {
      responseBody.detail = exception.message;
    }

    this.replyProblemDetailsJson(httpAdapter, response, responseBody);
  }
}
